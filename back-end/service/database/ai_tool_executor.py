    @staticmethod
    def _explain_query(
        user_id: str,
        db_config: dict,
        query: str,
        max_rows: int = 50,
    ) -> Dict:
        """Get the query execution plan for a read-only SQL statement.

        Lets the AI inspect the optimizer's plan for a SELECT/WITH query so
        it can diagnose slow queries, missing indexes, full-table scans, and
        bad join orderings. The system prompt advertises "performance"
        support — this tool is what backs that claim.

        Safety
        ------
        ``query`` is validated as read-only (SELECT/WITH only) via
        ``DatabaseSecurity.analyze_sql_query`` before being handed to the
        adapter. We deliberately do NOT use ``EXPLAIN ANALYZE`` on
        PostgreSQL/MySQL because ANALYZE actually executes the query — for
        arbitrary LLM-generated SQL on a shared pool, that's an
        unacceptable side-effect (locks, triggers via views, resource cost).

        Adapter dispatch
        ----------------
        Each adapter exposes:
          * ``explain_format`` — a tag the AI uses to interpret the rows
            ("json" for MySQL/PostgreSQL, "text" for SQL Server/Oracle).
          * ``run_explain(cursor, query)`` — handles DBMS-specific
            multi-statement orchestration (SQL Server SET SHOWPLAN_TEXT
            ON/OFF, Oracle EXPLAIN PLAN + DBMS_XPLAN.DISPLAY).

        Returns:
            ``{"success": True, "plan": rows, "plan_format": <str>,
            "query": <str>}`` on success, or ``{"error": ...}`` on failure.
        """
        from service.database.adapters import get_adapter
        from service.database.context_sync import get_default_context_sync
        from service.database.security import DatabaseSecurity

        if not query:
            return {"error": "Query is required"}

        context_sync = get_default_context_sync()
        connection = context_sync.get_connection(user_id)
        if not connection.get("connected"):
            return {"error": "Not connected to any database"}

        # Reuse the same read-only gate as execute_query so a malicious or
        # confused LLM cannot EXPLAIN an UPDATE/DELETE and observe which
        # rows would be touched.
        try:
            analysis = DatabaseSecurity.analyze_sql_query(query)
        except Exception as exc:
            return _database_failure("parse_explain_query", exc)
        if not analysis["is_safe"]:
            reason = "; ".join(analysis["warnings"]) or "query is not read-only"
            return {"error": f"Query blocked for security reasons: {reason}"}
        if analysis["query_type"] not in ("SELECT", "WITH"):
            return {
                "error": (
                    f"READ-ONLY MODE: Only SELECT/WITH queries are allowed "
                    f"for EXPLAIN. {analysis['query_type']} is blocked."
                )
            }

        db_type = connection.get("db_type", "postgresql")

        try:
            adapter = get_adapter(db_type)
            with get_tool_connection(db_config) as conn:
                cursor = None
                try:
                    cursor = conn.cursor()
                    raw_rows = adapter.run_explain(cursor, query)
                finally:
                    # FIX [H5]: close the cursor even when execute/fetch raises.
                    if cursor is not None:
                        try:
                            cursor.close()
                        except Exception:
                            pass

            # Bound the plan rows so a pathological plan (e.g. a 1000-way
            # join) cannot overflow the LLM context window.
            truncated = False
            if max_rows and isinstance(raw_rows, list) and len(raw_rows) > max_rows:
                raw_rows = raw_rows[:max_rows]
                truncated = True

            # Serialize the plan rows through the same JSON-safe pipeline
            # used by execute_query so DB-native types (datetime, Decimal,
            # UUID, bytes, ...) round-trip cleanly.
            # For JSON-format plans (MySQL/PG), the first column of the
            # single row is the JSON document; preserve it as a string so
            # the AI sees the raw JSON. For text-format plans (SQL Server/
            # Oracle), each row is a line of plan text.
            synthetic_col_names = [f"col_{i}" for i in range(len(raw_rows[0]) if raw_rows else 0)]
            plan_rows = AIToolExecutor._serialize_rows(
                raw_rows,
                synthetic_col_names,
            )

            # Best-effort: if the plan is a single-row single-column JSON
            # document (MySQL / PostgreSQL FORMAT JSON), unwrap it so the
            # AI sees the parsed JSON object instead of a JSON-encoded
            # string wrapped in another JSON string.
            if adapter.explain_format == "json" and len(plan_rows) == 1 and len(plan_rows[0]) >= 1:
                first_val = plan_rows[0][next(iter(plan_rows[0]))]
                if isinstance(first_val, str):
                    try:
                        import json as _json

                        unwrapped = _json.loads(first_val)
                        plan_rows = [unwrapped]
                    except Exception:
                        # Leave as-is; the AI can still read the raw string.
                        pass

            result = {
                "success": True,
                "plan": plan_rows,
                "plan_format": adapter.explain_format,
                "query": query,
                "row_count": len(plan_rows),
            }
            if truncated:
                result["truncated"] = True
            return result
        except Exception as e:
            return _database_failure("explain_query", e)

    @staticmethod
    def _get_table_details(user_id: str, db_config: dict, table_name: str) -> Dict:
        """Get detailed per-column schema for one table (types, defaults,
        PK, uniqueness, max_length).

        ``get_schema_overview`` only returns column names + PK flag. The AI
        needs data types, nullability, defaults, uniqueness, and max length
        to write type-correct SQL (e.g. choosing CAST vs CONVERT, knowing
        which columns accept NULL, knowing the max VARCHAR length before
        truncation). This tool fills that gap without forcing the AI to run
        a separate ``SELECT * FROM information_schema.columns`` query.

        Returns:
            ``{"success": True, "table": <name>, "columns": [...],
            "constraints": [...], "column_count": N}`` on success, or
            ``{"error": ...}`` on failure.
        """
        from service.database.adapters import get_adapter
        from service.database.context_sync import get_default_context_sync

        if not table_name:
            return {"error": "Table name is required"}

        context_sync = get_default_context_sync()
        connection = context_sync.get_connection(user_id)
        if not connection.get("connected"):
            return {"error": "Not connected to any database"}

        db_type = connection.get("db_type", "postgresql")
        database = connection.get("database")
        schema = connection.get("schema", "public")

        try:
            adapter = get_adapter(db_type)
            query, params = adapter.get_table_details_query(table_name, db_name=database, schema=schema)

            if query is None:
                return {"error": f"Table details query not supported for {db_type}"}

            columns: List[Dict] = []
            constraints: List[Dict] = []
            with get_tool_connection(db_config) as conn:
                cursor = None
                try:
                    cursor = conn.cursor()
                    cursor.execute(query, params)

                    for row in cursor.fetchall():
                        col = {
                            "name": row[0],
                            "data_type": row[1],
                            "is_nullable": (str(row[2]).upper() == "YES" if row[2] is not None else True),
                            "default": row[3],
                            "is_primary_key": bool(row[4]) if row[4] is not None else False,
                            "is_unique": bool(row[5]) if row[5] is not None else False,
                            "max_length": row[6],
                        }
                        columns.append(col)
                        # Synthesize constraint entries from the PK / UNIQUE
                        # flags so the AI sees a uniform "constraints" list
                        # regardless of adapter. Detailed constraint names
                        # are intentionally omitted — they vary by DBMS and
                        # the per-column flags already convey the semantic.
                        if col["is_primary_key"]:
                            constraints.append(
                                {
                                    "type": "PRIMARY KEY",
                                    "column": col["name"],
                                }
                            )
                        if col["is_unique"] and not col["is_primary_key"]:
                            constraints.append(
                                {
                                    "type": "UNIQUE",
                                    "column": col["name"],
                                }
                            )
                finally:
                    # FIX [H5]: close the cursor even when execute/fetch raises.
                    if cursor is not None:
                        try:
                            cursor.close()
                        except Exception:
                            pass

            return {
                "success": True,
                "table": table_name,
                "columns": columns,
                "constraints": constraints,
                "column_count": len(columns),
            }
        except Exception as e:
            return _database_failure("get_table_details", e)

