class AIToolExecutor:
    """Database tool implementations called directly by LangGraph @tool functions."""

    # Tool Implementations

    @staticmethod
    def _get_connection_status(user_id: str) -> Dict:
        """Get current connection status from context."""
        from service.database.context_sync import (
            get_default_context_sync,
        )

        context_sync = get_default_context_sync()

        connection = context_sync.get_connection(user_id)

        if connection.get("connected"):
            return {
                "connected": True,
                "db_type": connection.get("db_type"),
                "database": connection.get("database"),
                "host": connection.get("host"),
                "is_remote": connection.get("is_remote"),
                "schema": connection.get("schema"),
                "connected_at": connection.get("connected_at"),
            }
        else:
            return {"connected": False, "message": "Not connected to any database"}

    @staticmethod
    def _get_query_history(user_id: str) -> list[dict]:
        """Get recent SQL queries from database context memory."""
        from service.database.context_sync import (
            get_default_context_sync,
        )

        return get_default_context_sync().get_recent_queries(user_id)

    @staticmethod
    def _get_database_list(user_id: str, db_config: dict = None) -> Dict:
        """
        Get list of databases using db_config if available.

        Optimized to use passed db_config for direct database queries.
        """
        from service.database.context_sync import (
            get_default_context_sync,
        )

        context_sync = get_default_context_sync()

        connection = context_sync.get_connection(user_id)
        if not connection.get("connected"):
            return {"error": "Not connected to any database server"}
        if db_config:
            try:
                databases = AIToolExecutor._query_databases_with_config(db_config)
                return {
                    "databases": databases,
                    "current_database": connection.get("database"),
                    "count": len(databases),
                }
            except Exception as e:
                public = public_database_error(e)
                log_safe_exception(logger, "query_databases", e, public)
        current_db = connection.get("database")
        return {
            "databases": [current_db] if current_db else [],
            "current_database": current_db,
            "count": 1 if current_db else 0,
        }

    @staticmethod
    def _query_databases_with_config(db_config: dict) -> List[str]:
        """Query available databases using db_config (DBMS-agnostic)."""
        from service.database.adapters import get_adapter

        db_type = db_config.get("db_type", "postgresql")
        adapter = get_adapter(db_type)

        with get_tool_connection(db_config) as conn:
            cursor = None
            try:
                cursor = conn.cursor()
                query, params = adapter.get_databases_for_cache()
                cursor.execute(query, params) if params else cursor.execute(query)
                all_databases = [row[0] for row in cursor.fetchall()]
                system_dbs = adapter.get_system_databases()
                databases = [db for db in all_databases if db.lower() not in system_dbs]

                return databases
            finally:
                # FIX [H5]: close the cursor even when execute/fetch raises.
                if cursor is not None:
                    try:
                        cursor.close()
                    except Exception:
                        pass

    @staticmethod
    def _fetch_tables_with_config(db_config: dict, db_type: str, db_name: str = None) -> List[str]:
        """Fetch table names using db_config directly (DBMS-agnostic)."""
        from service.database.adapters import get_adapter

        tables = []
        adapter = get_adapter(db_type)

        with get_tool_connection(db_config) as conn:
            cursor = None
            try:
                cursor = conn.cursor()

                # Use explicit db_name if provided, else fall back to db_config
                effective_db_name = db_name or db_config.get("database", "")
                schema = db_config.get("schema", "public")
                query, params = adapter.get_all_tables_for_cache(effective_db_name, schema=schema)
                cursor.execute(query, params) if params else cursor.execute(query)

                tables = [row[0] for row in cursor.fetchall()]
            finally:
                # FIX [H5]: close the cursor even when execute/fetch raises.
                if cursor is not None:
                    try:
                        cursor.close()
                    except Exception:
                        pass

        logger.debug(f"Fetched {len(tables)} tables using db_config")
        return tables

    @staticmethod
    def _fetch_tables_and_columns(db_config: dict, db_type: str, db_name: str = None) -> tuple:
        """
        Fetch tables and columns with primary key info.

        Returns:
            tuple: (tables list, columns dict with {name, is_primary_key} objects)
        """
        tables = AIToolExecutor._fetch_tables_with_config(db_config, db_type, db_name)

        # Fetch columns with primary key info
        columns = AIToolExecutor._batch_fetch_columns(db_config, tables, db_type, db_name)

        return tables, columns

    @staticmethod
    def _batch_fetch_columns(db_config: dict, tables: List[str], db_type: str, db_name: str = None) -> Dict[str, List]:
        """
        Batch fetch columns for all tables in a single query (DBMS-agnostic).

        Returns dict where values are lists of column objects with:
        - name: column name
        - is_primary_key: True if column is part of primary key

        Much faster than individual queries for each table.
        """
        from service.database.adapters import get_adapter

        columns = {}

        if not tables:
            return columns

        adapter = get_adapter(db_type)
        # Use explicit db_name if provided, else fall back to db_config
        effective_db_name = db_name or db_config.get("database", "")
        schema = db_config.get("schema", "public")

        with get_tool_connection(db_config) as conn:
            cursor = None
            try:
                cursor = conn.cursor()
                query, params = adapter.get_batch_columns_for_tables(effective_db_name, tables, schema=schema)

                if query is None:
                    return {}

                cursor.execute(query, params)

                for row in cursor.fetchall():
                    table_name = row[0]
                    column_name = row[1]
                    column_key = row[2] if len(row) > 2 else ""

                    if table_name not in columns:
                        columns[table_name] = []
                    columns[table_name].append({"name": column_name, "is_primary_key": column_key == "PRI"})
            finally:
                # FIX [H5]: close the cursor even when execute/fetch raises.
                if cursor is not None:
                    try:
                        cursor.close()
                    except Exception:
                        pass
        for table in tables:
            if table not in columns:
                columns[table] = []

        logger.debug(f"Batch fetched columns for {len(columns)} tables")
        return columns

    @staticmethod
    def _execute_query(user_id: str, query: str, max_rows: int = 100, db_config: dict = None) -> Dict:
        """Execute a SQL query using provided db_config."""
        from service.database.context_sync import (
            get_default_context_sync,
        )

        context_sync = get_default_context_sync()

        if not query:
            return {"error": "Query is required"}

        connection = context_sync.get_connection(user_id)
        if not connection.get("connected"):
            return {"error": "Not connected to any database"}

        try:
            if db_config:
                logger.debug("Executing query with explicit db_config")
                result = AIToolExecutor._execute_query_with_db_config(db_config, connection, query, max_rows)
            else:
                return {"error": "No database config available. Please re-connect to the database."}
            database = connection.get("database")
            row_count = result.get("row_count", 0)
            status = "success" if result.get("status") == "success" else "error"
            context_sync.add_query(user_id, query, database, row_count, status)

            if result.get("status") == "success":
                # fetchmany(max_rows + 1) proves truncation but cannot prove an
                # exact database-wide total. Do not label the display count as
                # a total when additional rows may exist.
                total_rows = None if result.get("truncated") else result.get("row_count", 0)
                result_data = result.get("result", [])
                return {
                    "success": True,
                    "columns": result.get("columns", []),
                    "data": result_data,
                    "row_count": len(result_data),
                    "total_rows": total_rows,
                    "truncated": result.get("truncated", False),
                }
            else:
                return {
                    "success": False,
                    "error_code": result.get("error_code", "DB_OPERATION_FAILED"),
                    "error": result.get("message", "Database operation failed."),
                }

        except Exception as e:
            public = public_database_error(e)
            log_safe_exception(logger, "execute_query", e, public)

            # FIX [EC5]: mirror the missing-table cache-clear logic from
            # ``_execute_query_with_db_config`` here too, since this
            # outer scope has the actual ``user_id`` (the inner method
            # only has the connection dict, which does not carry
            # user_id). Different DBs phrase missing-table errors
            # differently — see the inner method for the full marker
            # list. Clearing the schema cache here ensures the next
            # AI turn refetches a fresh table list and stops
            # generating queries against the dropped table.
            try:
                err_msg_lower = str(e).lower()
                missing_table_markers = (
                    "relation" in err_msg_lower and "does not exist" in err_msg_lower,
                    "table or view does not exist" in err_msg_lower,
                    "invalid object name" in err_msg_lower,
                    "doesn't exist" in err_msg_lower and "table" in err_msg_lower,
                    "unknown table" in err_msg_lower,
                )
                if any(missing_table_markers) and user_id:
                    from service.context.context_service import ContextService

                    _db_for_clear = connection.get("database") if isinstance(connection, dict) else None
                    if _db_for_clear:
                        ContextService.clear_schema_context(user_id, _db_for_clear)
                        logger.info(
                            "Cleared schema cache for %s after missing-table error (outer)",
                            _db_for_clear,
                        )
            except Exception as clear_err:
                clear_public = public_tool_error(
                    "SCHEMA_CACHE_CLEAR_FAILED",
                    "Schema cache cleanup failed.",
                )
                log_safe_exception(
                    logger,
                    "clear_schema_cache_after_query_failure",
                    clear_err,
                    clear_public,
                )

            return {
                "success": False,
                "error_code": public.code,
                "error": public.message,
            }

    @staticmethod
    def _execute_query_with_db_config(db_config: Dict, connection: Dict, query: str, max_rows: int) -> Dict:
        """
        Execute a (read-only) query using an explicitly passed db_config.

        Timeout enforcement (FIX [H6]): the AI tool path used to skip the
        per-statement timeout that the user-facing ``execute_sql_query``
        sets. A cross-join DoS or slow analytical query generated by the
        LLM could hold a pool connection forever and eventually exhaust the
        pool for all users. We now set ``adapter.get_set_timeout_sql(30)``
        before executing the validated query.

        Cursor lifecycle (FIX [H5]): the cursor is created inside a
        ``try/finally`` so it is always closed even when execute/fetch
        raises.
        """
        import time

        from config import get_config
        from service.database.security import DatabaseSecurity

        Config = get_config()
        if not db_config:
            return {
                "status": "error",
                "message": "No database connection available. Please connect to a database first.",
            }

        db_type = db_config.get("db_type", "postgresql")

        # FIX [L10]: enforce the unified query-length limit on the AI path
        # too, so the agent cannot submit longer queries than the human
        # endpoint allows.
        if len(query) > Config.SQL_QUERY_MAX_LENGTH:
            return {
                "status": "error",
                "message": (f"Query too long. Maximum: {Config.SQL_QUERY_MAX_LENGTH} characters."),
            }

        # Security check
        analysis = DatabaseSecurity.analyze_sql_query(query)
        if not analysis["is_safe"]:
            return {
                "status": "error",
                "message": f"Query blocked for security reasons: {', '.join(analysis['warnings'])}",
            }

        if analysis["query_type"] not in ("SELECT", "WITH"):
            return {
                "status": "error",
                "message": f"READ-ONLY MODE: Only SELECT/WITH queries are allowed. {analysis['query_type']} is blocked.",
            }

        try:
            start_time = time.time()

            actual_max_rows = max_rows if max_rows else Config.MAX_QUERY_RESULTS

            from service.database.adapters import get_adapter

            adapter = get_adapter(db_type)

            with get_tool_connection(db_config) as conn:
                cursor = None
                try:
                    cursor = conn.cursor()

                    # FIX [EC6]: lightweight pre-query health check. A
                    # pooled connection that the DB server dropped
                    # (idle-timeout, restart, network blip) is only
                    # discovered when the user's query fails — and the
                    # broken connection is then *returned to the pool*
                    # and handed to the next query, producing cascading
                    # failures across every user sharing the pool. We
                    # issue a no-op SELECT first; if it raises, we
                    # surface a clear ConnectionError so the user
                    # reconnects, and mark the conn as ``_failed`` so
                    # ``ConnectionManager.return_connection`` discards
                    # it instead of pooling it. We deliberately do NOT
                    # auto-retry — retrying a non-idempotent read is
                    # risky.
                    try:
                        cursor.execute(adapter.get_health_check_sql())
                        cursor.fetchone()
                    except Exception as health_err:
                        health_public = public_database_error(health_err)
                        log_safe_exception(
                            logger,
                            "database_health_check",
                            health_err,
                            health_public,
                        )
                        try:
                            setattr(conn, "_failed", True)
                        except Exception:
                            pass
                        raise ConnectionError("Connection lost, please reconnect") from health_err

                    # FIX [EC3]: Oracle has no SET TIMEOUT SQL statement —
                    # its timeout is enforced via the oracledb driver's
                    # per-connection ``call_timeout`` attribute. Detect
                    # the method via getattr and apply it directly to the
                    # connection before issuing the query. Other adapters
                    # (MySQL/PostgreSQL/SQL Server) use the SQL-string
                    # path below and do not define ``set_session_timeout``
                    # so this branch is a no-op for them.
                    set_session_timeout_fn = getattr(adapter, "set_session_timeout", None)
                    if callable(set_session_timeout_fn):
                        try:
                            set_session_timeout_fn(conn, 30)
                        except Exception as timeout_err:
                            timeout_public = public_database_error(timeout_err)
                            log_safe_exception(
                                logger,
                                "set_database_session_timeout",
                                timeout_err,
                                timeout_public,
                            )

                    # FIX [H6]: set a per-statement timeout BEFORE executing
                    # the LLM-issued query. Without this a cross-join DoS
                    # would hang a pool connection until the pool was
                    # exhausted. Mirrors operations.execute_sql_query.
                    timeout_sql = adapter.get_set_timeout_sql(timeout_seconds=30)
                    if timeout_sql:
                        try:
                            cursor.execute(timeout_sql)
                        except Exception as timeout_err:
                            # Best-effort: some adapters (e.g. Oracle, SQL
                            # Server) return None and skip this entirely; if
                            # the SET itself fails we still proceed because
                            # the user-facing path also tolerates this.
                            timeout_public = public_database_error(timeout_err)
                            log_safe_exception(
                                logger,
                                "set_database_statement_timeout",
                                timeout_err,
                                timeout_public,
                            )
                    if db_type == "postgresql":
                        schema = connection.get("schema", "public")
                        # Validate schema name to prevent SQL injection
                        if not re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", schema):
                            raise ValueError(f"Invalid schema name: {schema}")
                        # FIX [M15]: use psycopg2.sql.Identifier to safely
                        # interpolate the schema name into SET search_path,
                        # rather than f-string interpolation. Even though the
                        # regex above rejects non-identifier characters, the
                        # Identifier-based approach is defense-in-depth and
                        # also handles edge cases (reserved words, mixed case).
                        try:
                            from psycopg2 import sql as _pg_sql

                            cursor.execute(_pg_sql.SQL("SET search_path TO {}").format(_pg_sql.Identifier(schema)))
                        except ImportError:
                            # psycopg2 not available — fall back to the
                            # regex-validated interpolation. The regex above
                            # ensures the schema is a safe identifier.
                            cursor.execute(f"SET search_path TO {schema}")
                    cursor.execute(query)
                    rows = cursor.fetchmany(actual_max_rows + 1)

                    end_time = time.time()
                    execution_time = round((end_time - start_time) * 1000, 2)
                    column_names = adapter.get_column_names_from_cursor(cursor)
                finally:
                    # FIX [H5]: close the cursor even when execute/fetch raises.
                    if cursor is not None:
                        try:
                            cursor.close()
                        except Exception:
                            pass
            fetched_count = len(rows)
            truncated = fetched_count > actual_max_rows
            if truncated:
                rows = rows[:actual_max_rows]
            result_data = AIToolExecutor._serialize_rows(rows, column_names)
            row_count = len(result_data)

            logger.debug("AI tool executed query: %d rows in %.2fms", row_count, execution_time)

            return {
                "status": "success",
                "columns": column_names,
                "result": result_data,
                "row_count": row_count,
                "truncated": truncated,
                "execution_time_ms": execution_time,
            }

        except Exception as e:
            public = public_database_error(e)
            log_safe_exception(logger, "execute_query_with_db_config", e, public)

            # FIX [EC5]: if the error indicates a missing/dropped table
            # (different DBs phrase this differently: PG says
            # "relation ... does not exist", SQL Server says "invalid
            # object name", Oracle says "table or view does not exist",
            # MySQL says "table ... doesn't exist"), invalidate the
            # schema cache for this database so the next call refetches
            # a fresh table list. Without this, the dropped table would
            # stay in the cache and the AI would keep generating queries
            # against it on every subsequent turn. We only clear when we
            # have the user_id+database context needed to target the
            # cache entry; failure to clear is non-blocking (the
            # query-error response is still returned).
            err_msg_lower = str(e).lower()
            missing_table_markers = (
                "relation" in err_msg_lower and "does not exist" in err_msg_lower,
                "table or view does not exist" in err_msg_lower,
                "invalid object name" in err_msg_lower,
                "doesn't exist" in err_msg_lower and "table" in err_msg_lower,
                "unknown table" in err_msg_lower,
            )
            if any(missing_table_markers):
                _user_id_for_clear = connection.get("user_id") if isinstance(connection, dict) else None
                _db_for_clear = connection.get("database") if isinstance(connection, dict) else None
                # The caller (_execute_query) has the user_id; we expose
                # the cache-clear request via a flag in the returned
                # dict so the caller can perform it with user_id in
                # hand. We also best-effort clear here using whatever
                # identity info we can recover from the connection dict.
                try:
                    if _user_id_for_clear and _db_for_clear:
                        from service.context.context_service import ContextService

                        ContextService.clear_schema_context(_user_id_for_clear, _db_for_clear)
                        logger.info(
                            "Cleared schema cache for %s after missing-table error",
                            _db_for_clear,
                        )
                except Exception as clear_err:
                    clear_public = public_tool_error(
                        "SCHEMA_CACHE_CLEAR_FAILED",
                        "Schema cache cleanup failed.",
                    )
                    log_safe_exception(
                        logger,
                        "clear_schema_cache_after_db_failure",
                        clear_err,
                        clear_public,
                    )

            return {
                "status": "error",
                "error_code": public.code,
                "message": public.message,
            }

    @staticmethod
    def _serialize_rows(rows: List, column_names: List[str]) -> List[Dict]:
        """
        Convert database rows to JSON-serializable dictionaries.

        Handles special types: datetime, date, time, timedelta, Decimal,
        bytes/bytearray, UUID, Enum, IP addresses, and falls back to
        ``str(value)`` (with a debug log) for any other non-JSON-serializable
        type encountered.

        FIX [EC1]: previously only ``datetime`` (via ``isoformat``), ``bytes``,
        and ``Decimal`` were handled. PostgreSQL UUIDs came back as
        ``uuid.UUID`` objects, Enums/IPs/ranges came back as their native
        Python types, and ``json.dumps`` later raised ``TypeError``. That
        ``TypeError`` was caught at the LangGraph ``tool_executor`` layer
        and the LLM only saw a generic ``<tool_execution_error>`` even
        though the query had succeeded and its rows had been persisted to
        Firestore. We now serialize all common PostgreSQL/MySQL/Oracle
        custom types so the rows round-trip cleanly through ``json.dumps``.

        FIX [EC2]: previously all ``bytes`` values were decoded as UTF-8
        with ``errors="replace"``, silently corrupting binary BLOBs
        (images, PDFs, encrypted data) by replacing every non-UTF-8 byte
        with U+FFFD. We now first attempt a strict UTF-8 decode; if that
        fails OR the original bytes contain a NUL byte (a strong signal
        of binary content), we return a ``0x``-prefixed hex string
        (truncated to 256 hex chars / 128 bytes) so the LLM can at least
        see the value's shape and length without payload corruption.
        """
        # FIX [EC1]: import all custom-type modules up-front (cheap — these
        # are all stdlib and idempotent).
        import datetime as _dt
        import decimal as _decimal
        import enum as _enum
        import ipaddress as _ip
        import uuid as _uuid

        Decimal = _decimal.Decimal

        result_data = []
        for row in rows:
            row_dict = {}
            for i, col in enumerate(column_names):
                value = row[i]
                # Handle non-serializable types
                if value is None:
                    pass  # None is JSON serializable
                elif isinstance(value, bool):
                    # bool is a subclass of int; keep it as-is (JSON-native).
                    pass
                elif isinstance(value, (str, int, float)):
                    pass  # JSON-native
                elif isinstance(value, Decimal):
                    # FIX [EC1]: keep existing Decimal handling.
                    value = float(value)
                elif isinstance(value, _uuid.UUID):
                    # FIX [EC1]: PostgreSQL UUID columns come back as
                    # uuid.UUID objects — str() yields the canonical form.
                    value = str(value)
                elif isinstance(value, _enum.Enum):
                    # FIX [EC1]: Enum columns (e.g. Postgres enums) — use
                    # ``.value`` so the LLM sees the raw stored value, not
                    # ``MyEnum.NAME``.
                    value = value.value
                elif isinstance(value, (_ip.IPv4Address, _ip.IPv6Address)):
                    # FIX [EC1]: inet/cidr columns.
                    value = str(value)
                elif isinstance(value, _dt.timedelta):
                    # FIX [EC1]: PostgreSQL interval columns come back as
                    # datetime.timedelta; isoformat() does not exist on
                    # timedelta. Serialize as total seconds (float).
                    value = value.total_seconds()
                elif isinstance(value, _dt.time):
                    # FIX [EC1]: time columns — must come BEFORE the
                    # ``hasattr(value, "isoformat")`` branch below because
                    # datetime.datetime also has isoformat; ordering by
                    # specificity avoids mis-classification.
                    value = value.isoformat()
                elif isinstance(value, _dt.date):
                    # FIX [EC1]: date columns (datetime.date is the parent
                    # of datetime.datetime, so check date AFTER datetime).
                    value = value.isoformat()
                elif isinstance(value, _dt.datetime):
                    value = value.isoformat()
                elif isinstance(value, (bytes, bytearray)):
                    # FIX [EC2]: detect binary BLOBs vs. text. A NUL byte
                    # is a strong indicator of binary content; a strict
                    # UTF-8 decode failure is the other. Either way we
                    # hex-encode the bytes (truncated) instead of silently
                    # corrupting them with errors="replace".
                    raw = bytes(value)
                    is_binary = b"\x00" in raw
                    if not is_binary:
                        try:
                            value = raw.decode("utf-8")
                        except UnicodeDecodeError:
                            is_binary = True
                    if is_binary:
                        hex_str = raw.hex()
                        # Truncate to 256 hex chars (128 bytes) so a 50MB
                        # BLOB cannot blow up the LLM context window.
                        if len(hex_str) > 256:
                            hex_str = hex_str[:256] + f"...<truncated, {len(raw)} bytes total>"
                        logger.debug(
                            "Binary BLOB column %r hex-encoded (%d bytes)",
                            col,
                            len(raw),
                        )
                        value = f"0x{hex_str}"
                elif hasattr(value, "isoformat"):  # leftover datetime-likes
                    value = value.isoformat()
                else:
                    # FIX [EC1]: catch-all for any other non-JSON-serializable
                    # type (e.g. numpy scalars, custom ORM types, range
                    # types). ``str()`` is the safest universal fallback;
                    # we log at debug so a noisy type shows up in dev logs
                    # without spamming production.
                    logger.debug(
                        "Falling back to str() for non-serializable value of type %r in column %r",
                        type(value).__name__,
                        col,
                    )
                    value = str(value)
                row_dict[col] = value
            result_data.append(row_dict)

        return result_data

