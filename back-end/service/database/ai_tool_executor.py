        if not connection.get("connected"):
            return {"error": "Not connected to any database"}

        db_type = connection.get("db_type", "postgresql")
        database = connection.get("database")
        schema = connection.get("schema", "public")

        try:
            adapter = get_adapter(db_type)

            views: List[str] = []
            materialized_views: List[str] = []

            with get_tool_connection(db_config) as conn:
                cursor = None
                try:
                    cursor = conn.cursor()
                    v_query, v_params = adapter.get_views(schema=schema, db_name=database)
                    if v_query:
                        cursor.execute(v_query, v_params) if v_params else cursor.execute(v_query)
                        views = [row[0] for row in cursor.fetchall()]

                    # Materialized views (only PostgreSQL and Oracle
                    # support them; the base adapter returns None).
                    mv = adapter.get_materialized_views(schema=schema, db_name=database)
                    if mv:
                        mv_query, mv_params = mv
                        if mv_query:
                            cursor.execute(mv_query, mv_params) if mv_params else cursor.execute(mv_query)
                            materialized_views = [row[0] for row in cursor.fetchall()]
                finally:
                    # FIX [H5]: close the cursor even when execute/fetch raises.
                    if cursor is not None:
                        try:
                            cursor.close()
                        except Exception:
                            pass

            return {
                "success": True,
                "views": views,
                "materialized_views": materialized_views,
                "count": len(views) + len(materialized_views),
            }
        except Exception as e:
            return _database_failure("list_views", e)
