"""
Database Tool Executors

Contains the actual DB execution logic for each LangGraph tool.
Called directly by @tool functions in agent/tools.py — no dispatcher needed.

Cursor lifecycle
----------------
Every helper that opens a cursor wraps it in ``try/finally`` (FIX [H5])
so the cursor is always closed even when ``execute`` raises (syntax,
permission, timeout). A leaked cursor keeps the underlying connection in
an aborted-transaction state and gradually exhausts the pool.

Timeout enforcement
-------------------
User-facing queries run through ``operations.execute_sql_query``, which
sets a per-statement timeout (``SET MAX_EXECUTION_TIME`` / ``statement_timeout``)
before executing the query. The AI tool path used to skip this (FIX [H6]),
so a cross-join DoS generated by the LLM could hang the pool forever.
We now set ``adapter.get_set_timeout_sql(timeout_seconds=30)`` before the LLM-issued
query is executed.
"""

import logging
import re
from contextlib import contextmanager
from typing import Dict, List, Optional

from core.errors import log_safe_exception, public_database_error, public_tool_error

logger = logging.getLogger(__name__)


def _database_failure(operation: str, exc: BaseException, *, status_style: bool = False) -> Dict:
    """Return the established executor error shape with stable public detail."""
    public = public_database_error(exc)
    log_safe_exception(logger, operation, exc, public)
    if status_style:
        return {
            "status": "error",
            "error_code": public.code,
            "message": public.message,
        }
    return {
        "success": False,
        "error_code": public.code,
        "error": public.message,
    }


# CONNECTION HELPER (Reusable for all tools)


@contextmanager
def get_tool_connection(db_config: dict):
    """
    Context manager for getting a database connection from db_config.

    Delegates to the singleton ConnectionManager so that the pool created at
    connect_db time is reused across all tool calls, avoiding the overhead of
    creating and tearing down a fresh pool on every invocation.

    Supports all database types via the adapter pattern:
    - PostgreSQL (psycopg2)
    - MySQL (mysql-connector)
    - SQL Server (pymssql)
    - Oracle (oracledb)

    Usage:
        with get_tool_connection(db_config) as conn:
            cursor = conn.cursor()
            cursor.execute("SELECT 1")
    """
    from service.database.connection_manager import (
        get_connection_manager,
    )

    manager = get_connection_manager()
    with manager.get_connection_context(db_config) as conn:
        yield conn


