    @staticmethod
    def _get_schema_overview(user_id: str, target_tables: Optional[List[str]] = None, db_config: dict = None) -> Dict:
        """
        Get an overview of the schema including columns and foreign keys for
        specific or all tables.

        Cache freshness (FIX [L11]): when ``target_tables`` is provided and
        one or more requested tables are NOT present in the cached schema
        context (e.g. a table created after the cache was populated), we
        explicitly fetch the missing tables' columns from the database,
        update the cache, and mark the missing tables in the response so the
        AI does not silently operate on incomplete schema. Previously these
        missing tables were dropped from the columns dict without any
        signal, so the AI would generate queries against stale schema.
        """
        from service.database.context_sync import (
            get_default_context_sync,
        )

        context_sync = get_default_context_sync()

        connection = context_sync.get_connection(user_id)
        if not connection.get("connected"):
            return {"error": "Not connected to any database"}

        database = connection.get("database")
        db_type = connection.get("db_type", "postgresql")

        try:
            schema_context = context_sync.get_schema_context(user_id, database)
            if schema_context:
                cached_tables = schema_context.get("tables", [])
                cached_columns = dict(schema_context.get("columns", {}))
                tables = target_tables if target_tables else cached_tables
                if len(tables) > 50:
                    # FIX [EC7]: truncate the available_tables list so a
                    # database with 10,000+ tables does not produce a
                    # 50K+ token error response that overflows the LLM
                    # context window. We send the first 200 names plus a
                    # total count + truncated flag so the AI can decide
                    # to use the target_tables parameter for specificity.
                    _total = len(cached_tables)
                    _list = cached_tables[:200]
                    return {
                        "error": "Context Window Protection",
                        "message": (
                            f"You requested {len(tables)} tables, which "
                            "exceeds the safe limit of 50. Please narrow "
                            "down your target_tables list further. "
                            f"Showing first 200 of {_total} tables. Use "
                            "target_tables parameter to request specific "
                            "tables."
                        ),
                        "available_tables": _list,
                        "total_table_count": _total,
                        "truncated_table_list": _total > len(_list),
                    }

                # FIX [L11]: explicitly identify requested tables that are
                # NOT in the cache (e.g. recently-created tables). Fetch
                # their columns fresh and merge into the cached map so the
                # AI does not silently operate on incomplete schema.
                missing_tables = [t for t in tables if t not in cached_columns]
                refreshed_missing: List[str] = []
                if missing_tables and db_config is not None:
                    try:
                        fresh_columns = AIToolExecutor._batch_fetch_columns(
                            db_config, missing_tables, db_type, db_name=database
                        )
                        if fresh_columns:
                            cached_columns.update(fresh_columns)
                            refreshed_missing = [t for t in missing_tables if t in fresh_columns]
                            # Best-effort async schema refresh: persist the
                            # freshly-learned tables back into the context
                            # cache so subsequent calls hit. We update the
                            # cached table list as well so the new tables
                            # appear in future available_tables responses.
                            try:
                                updated_tables = list(dict.fromkeys(cached_tables + refreshed_missing))
                                context_sync.store_schema_context(
                                    user_id,
                                    database,
                                    updated_tables,
                                    cached_columns,
                                )
                            except Exception as refresh_err:
                                refresh_public = public_database_error(refresh_err)
                                log_safe_exception(
                                    logger,
                                    "refresh_schema_context",
                                    refresh_err,
                                    refresh_public,
                                )
                    except Exception as fetch_err:
                        fetch_public = public_database_error(fetch_err)
                        log_safe_exception(
                            logger,
                            "fetch_missing_schema_tables",
                            fetch_err,
                            fetch_public,
                        )

                # Build the columns dict for the requested tables. Tables
                # that are still missing (could not be refreshed) get an
                # explicit empty entry plus a marker so the AI knows.
                columns: Dict[str, List] = {}
                unrefreshed_missing: List[str] = []
                for t in tables:
                    if t in cached_columns:
                        columns[t] = cached_columns[t]
                    else:
                        columns[t] = []
                        unrefreshed_missing.append(t)
                all_foreign_keys_result = AIToolExecutor._get_foreign_keys(user_id, db_config=db_config)
                fks = all_foreign_keys_result.get("foreign_keys", [])
                if target_tables:
                    target_set = set(target_tables)
                    fks = [
                        fk
                        for fk in fks
                        if fk.get("table_name") in target_set or fk.get("referenced_table") in target_set
                    ]

                response = {
                    "database": database,
                    "tables": tables,
                    "columns": columns,
                    "foreign_keys": fks,
                    "table_count": len(tables),
                    "foreign_key_count": len(fks),
                    "source": "context",
                }
                # FIX [L11]: surface missing-table info so the AI agent
                # can decide whether to retry / re-fetch schema.
                if refreshed_missing or unrefreshed_missing:
                    response["refreshed_missing_tables"] = refreshed_missing
                    response["unrefreshed_missing_tables"] = unrefreshed_missing
                    response["schema_partial"] = bool(unrefreshed_missing)
                return response
            all_tables = AIToolExecutor._fetch_tables_with_config(db_config, db_type, db_name=database)

            if not all_tables:
                return {
                    "database": database,
                    "tables": [],
                    "columns": {},
                    "foreign_keys": [],
                    "message": "No tables found",
                }

            # FIX [EC5]: detect tables that are still in the cached schema
            # context but were DROPPED from the DB. The cache key is
            # ``database`` only (see context_service.get_schema_context),
            # and FIX [L11] only handled the *new* table case. A dropped
            # table would otherwise linger in the cache, the AI would
            # generate queries against it, the DB would return "relation
            # does not exist", and the cache would NOT be invalidated —
            # repeating the failure on every subsequent call. We look at
            # the raw (TTL-bypassing) cache entry to compute the diff;
            # the subsequent ``store_schema_context`` call replaces the
            # cache so the dropped tables are physically removed.
            try:
                from service.context.context_service import ContextService

                raw_ctx = ContextService._get_context(user_id) or {}
                raw_schemas = raw_ctx.get("database_schemas", {}) or {}
                raw_entry = raw_schemas.get(database) or {}
                cached_table_list = list(raw_entry.get("tables", []) or [])
                if cached_table_list:
                    fresh_set = set(all_tables)
                    stale_tables = [t for t in cached_table_list if t not in fresh_set]
                    if stale_tables:
                        logger.info(
                            "Removed %d stale table(s) from schema cache: %s",
                            len(stale_tables),
                            stale_tables[:50],
                        )
                        # The cache is replaced wholesale below by
                        # ``store_schema_context(user_id, database,
                        # all_tables, columns)`` — no explicit per-table
                        # delete needed. We log so operators can see the
                        # churn.
            except Exception as stale_err:
                stale_public = public_database_error(stale_err)
                log_safe_exception(
                    logger,
                    "detect_stale_schema_tables",
                    stale_err,
                    stale_public,
                )
            if target_tables:
                tables = target_tables
                if len(tables) > 50:
                    # FIX [EC7]: truncate available_tables (see above for
                    # full rationale). Same 200-name cap + total count +
                    # truncated flag, so an LLM hitting this branch on a
                    # 10k-table database still gets a usable response.
                    _total = len(all_tables)
                    _list = all_tables[:200]
                    return {
                        "error": "Context Window Protection",
                        "message": (
                            f"You requested {len(tables)} tables, which "
                            "exceeds the safe limit of 50. Please narrow "
                            "down your target_tables list further. "
                            f"Showing first 200 of {_total} tables. Use "
                            "target_tables parameter to request specific "
                            "tables."
                        ),
                        "available_tables": _list,
                        "total_table_count": _total,
                        "truncated_table_list": _total > len(_list),
                    }
            else:
                if len(all_tables) > 50:
                    # FIX [EC7]: same truncation pattern as above.
                    _total = len(all_tables)
                    _list = all_tables[:200]
                    return {
                        "error": "Context Window Protection",
                        "message": (
                            f"This database contains {_total} tables. "
                            "Visualizing or fetching the entire schema at "
                            "once will exceed context limits. Please "
                            "specify a focused list of 'target_tables' to "
                            f"explore. Showing first 200 of {_total} tables."
                        ),
                        "available_tables": _list,
                        "total_table_count": _total,
                        "truncated_table_list": _total > len(_list),
                    }
                tables = all_tables
            columns = AIToolExecutor._batch_fetch_columns(db_config, tables, db_type, db_name=database)
            context_sync.store_schema_context(user_id, database, all_tables, columns)
            all_foreign_keys_result = AIToolExecutor._get_foreign_keys(user_id, db_config=db_config)
            fks = all_foreign_keys_result.get("foreign_keys", [])
            if target_tables:
                target_set = set(target_tables)
                fks = [
                    fk for fk in fks if fk.get("table_name") in target_set or fk.get("referenced_table") in target_set
                ]

            return {
                "database": database,
                "tables": tables,
                "columns": columns,
                "foreign_keys": fks,
                "table_count": len(tables),
                "foreign_key_count": len(fks),
                "source": "fresh",
            }
        except Exception as e:
            return _database_failure("get_schema_overview", e)

